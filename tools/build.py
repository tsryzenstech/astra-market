"""Builds dist/com.astra.market.apkg.

  python3 tools/build.py --astra ../astra [--build-number N]

config.json "server" becomes app/qml/Server.js, so changing the server
address is a one-line change here followed by a new release. The
versionCode is app.json's plus the build number (the CI run number), so
every release is an update for the phones.
"""
import argparse
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--astra", default=os.environ.get("ASTRA_SRC", os.path.join(ROOT, "..", "astra")),
                    help="astraOS source tree (for tools/apkgtool)")
    ap.add_argument("--build-number", type=int, default=int(os.environ.get("BUILD_NUMBER", "0")))
    ap.add_argument("-o", "--out", default=os.path.join(ROOT, "dist"))
    args = ap.parse_args()

    config = json.load(open(os.path.join(ROOT, "config.json"), encoding="utf-8"))
    server = config["server"].rstrip("/")
    with open(os.path.join(ROOT, "app", "qml", "Server.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/build.py from config.json. Do not edit.\n.pragma library\n")
        f.write("var url = " + json.dumps(server) + "\n")

    app_dir = os.path.join(ROOT, "build", "app")
    subprocess.run([sys.executable, "-c", "import shutil,sys; shutil.rmtree(sys.argv[2], ignore_errors=True); shutil.copytree(sys.argv[1], sys.argv[2])",
                    os.path.join(ROOT, "app"), app_dir], check=True)
    manifest_path = os.path.join(app_dir, "app.json")
    manifest = json.load(open(manifest_path, encoding="utf-8"))
    manifest["versionCode"] = int(manifest["versionCode"]) + args.build_number
    if args.build_number:
        manifest["version"] = f'{manifest["version"]}.{args.build_number}'
    json.dump(manifest, open(manifest_path, "w", encoding="utf-8", newline="\n"), indent=4, ensure_ascii=False)

    os.makedirs(args.out, exist_ok=True)
    out = os.path.join(args.out, "com.astra.market.apkg")
    subprocess.run([sys.executable, os.path.join(args.astra, "tools", "apkgtool", "apkgtool.py"), "pack", app_dir, "-o", out], check=True)
    with open(os.path.join(args.out, "release.json"), "w", encoding="utf-8") as f:
        json.dump({"version": manifest["version"], "versionCode": manifest["versionCode"], "server": server}, f, indent=2)
    print(f'{out}: {manifest["version"]} ({manifest["versionCode"]}) for {server}')


if __name__ == "__main__":
    main()
